/**
 * Generates `lib/model-manifest.ts` — the model URLs, each carrying a hash of
 * its own bytes.
 *
 * WHY THIS EXISTS
 * `/models/*` is served `Cache-Control: immutable, max-age=31536000`, which is
 * right for a multi-megabyte asset — but only if the URL changes when the bytes
 * do. It did not. `archit.glb` was replaced three times at the same path, so
 * any browser that had loaded the site kept the first version pinned for a
 * year and showed a stale model no matter what was deployed.
 *
 * Appending a content hash makes the header honest: same bytes, same URL,
 * cached forever; new bytes, new URL, fetched immediately.
 *
 * Runs on `prebuild`, so it cannot drift from what is in `public/models/`.
 *
 * Usage: node scripts/write-model-manifest.mjs
 */
import { createHash } from 'crypto';
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const MODELS_DIR = 'public/models';
const OUT = 'lib/model-manifest.ts';

const files = readdirSync(MODELS_DIR)
  .filter((f) => f.endsWith('.glb'))
  .sort();

if (files.length === 0) {
  console.error(`no .glb files in ${MODELS_DIR}`);
  process.exit(1);
}

const entries = files.map((file) => {
  const bytes = readFileSync(join(MODELS_DIR, file));
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 8);
  // camelCase key: archit.glb -> archit, macbook.glb -> macbook
  const key = file.replace(/\.glb$/, '').replace(/[-_](.)/g, (_, c) => c.toUpperCase());
  return { key, file, hash, size: bytes.length };
});

const body = `// GENERATED by scripts/write-model-manifest.mjs — do not edit.
//
// Each URL carries a hash of the file's bytes so that the year-long
// \`immutable\` cache header on /models/* stays truthful: replacing a model
// changes its URL, so browsers fetch it instead of serving a stale copy.

export const MODEL_URLS = {
${entries.map((e) => `  /** ${e.file} — ${(e.size / 1048576).toFixed(2)}MB */\n  ${e.key}: '/models/${e.file}?v=${e.hash}',`).join('\n')}
} as const;

export type ModelKey = keyof typeof MODEL_URLS;
`;

writeFileSync(OUT, body);
for (const e of entries) {
  console.log(`  ${e.file.padEnd(16)} ${e.hash}  ${(e.size / 1048576).toFixed(2)}MB`);
}
console.log(`wrote ${OUT}`);
